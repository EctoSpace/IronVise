//! The release-blocking migration fixture: a v0.6.4 **Postgres** ledger.
//!
//! Needs a database, so it is gated like the other integration tests:
//!
//!   ./scripts/test-integration.sh
//!   # or: DATABASE_URL=postgres://… cargo test --features integration
//!
//! ## Why Postgres is the one that blocks the release
//!
//! v0.6.4's SQLite backend hashed one serialisation of the payload and stored
//! another, so it could not verify its own output - see
//! `fixtures/README.md` and the `v064_sqlite_*` tests. There is therefore no
//! verifiable v0.6.4 SQLite ledger anywhere to stay compatible with.
//!
//! Postgres is different, and it is what production users ran. Its verifier
//! re-serialised the typed value (`&row.payload.0`) rather than the stored
//! JSONB, so both sides agreed on key ordering and the chain verified.
//! Confirmed by building v0.6.4 and asking it to check a ledger it had just
//! written: `V064_PG_SELF_VERIFY=true`.
//!
//! So this fixture represents the only class of v0.6.4 ledger that exists and
//! verifies. If 0.8.0 breaks it, 0.8.0 breaks real users' evidence.
//!
//! The fixture is committed as plain SQL rather than a binary dump: it stays
//! reviewable in a diff and does not depend on a `pg_dump` version. It was
//! generated by checking out v0.6.4 and running a generator against that
//! tree's own Postgres backend - never by this release.

#![cfg(feature = "integration")]

use ectoledger::hash::{HashScheme, verify_content_hash_any_scheme};
use ectoledger::ledger::postgres::verify_chain;
use ectoledger::schema::EventPayload;
use serial_test::serial;
use sqlx::postgres::PgPoolOptions;
use sqlx::{Executor, PgPool};

const FIXTURE_SQL: &str = include_str!("fixtures/ledger-v0.6.4-postgres.sql");
const EXPECTED_EVENTS: usize = 7;

async fn pool() -> PgPool {
    let url = std::env::var("DATABASE_URL")
        .expect("DATABASE_URL must be set; run ./scripts/test-integration.sh");
    let pool = PgPoolOptions::new()
        .max_connections(4)
        .connect(&url)
        .await
        .expect("connect to Postgres");
    sqlx::migrate!("./migrations")
        .run(&pool)
        .await
        .expect("current migrations apply");
    pool
}

/// Load the fixture into the live schema.
///
/// The dump carries `psql` meta-commands and `SET` statements that sqlx cannot
/// execute, so only the INSERTs are replayed. They are already in
/// foreign-key-safe order: sessions, then events, then signatures.
async fn load_fixture(pool: &PgPool) {
    // The immutability trigger refuses UPDATE and DELETE, so clearing has to go
    // around it. This is a scratch test database; the trigger is doing its job
    // and is restored by the migration on the next run.
    for stmt in [
        "ALTER TABLE agent_events DISABLE TRIGGER USER",
        "DELETE FROM agent_event_signatures",
        "DELETE FROM agent_events",
        "DELETE FROM agent_sessions",
    ] {
        pool.execute(stmt).await.expect("clearing fixture tables");
    }

    for line in FIXTURE_SQL.lines() {
        let line = line.trim();
        if line.starts_with("INSERT INTO") {
            pool.execute(line).await.unwrap_or_else(|e| {
                panic!(
                    "loading fixture row failed: {e}\n{}",
                    &line[..line.len().min(120)]
                )
            });
        }
    }

    pool.execute("ALTER TABLE agent_events ENABLE TRIGGER USER")
        .await
        .expect("re-enabling the immutability trigger");
}

type EventRow = (
    i64,
    String,
    String,
    sqlx::types::Json<EventPayload>,
    Option<uuid::Uuid>,
    chrono::DateTime<chrono::Utc>,
);

async fn events(pool: &PgPool) -> Vec<EventRow> {
    sqlx::query_as::<_, EventRow>(
        "SELECT sequence, previous_hash, content_hash, payload, session_id, created_at
         FROM agent_events ORDER BY sequence ASC",
    )
    .fetch_all(pool)
    .await
    .expect("reading events")
}

#[tokio::test]
#[serial]
async fn a_v064_postgres_ledger_verifies_under_the_current_release() {
    let pool = pool().await;
    load_fixture(&pool).await;

    let rows = events(&pool).await;
    assert_eq!(
        rows.len(),
        EXPECTED_EVENTS,
        "fixture did not load completely"
    );

    let tip = rows.last().expect("non-empty").0;
    assert!(
        verify_chain(&pool, 0, tip).await.expect("verification"),
        "A Postgres ledger written by v0.6.4 no longer verifies under this \
         release. These are the only v0.6.4 ledgers that exist and verify, so \
         this is a compatibility break affecting real users' evidence - not a \
         test to update."
    );
}

#[tokio::test]
#[serial]
async fn it_verifies_through_the_legacy_v1_scheme() {
    // v0.6.4 predates the canonical v2 input, so every event must match the
    // legacy layout. If this starts reporting V2 the fixture was regenerated by
    // the current code, which would make the test prove nothing.
    let pool = pool().await;
    load_fixture(&pool).await;

    for (seq, prev_hash, ch, payload, sid, created_at) in events(&pool).await {
        // Postgres normalises JSONB, so the stored text is not the text that was
        // hashed. Verification re-serialises the typed value, exactly as both
        // v0.6.4 and this release do.
        let payload_json = serde_json::to_string(&payload.0).expect("re-serialize");
        let scheme = verify_content_hash_any_scheme(
            &prev_hash,
            seq,
            &payload_json,
            sid.map(|u| u.to_string()).as_deref(),
            Some(&created_at.to_rfc3339()),
            &ch,
        )
        .unwrap_or_else(|| panic!("event {seq} matches no known hash scheme"));

        assert_eq!(
            scheme,
            HashScheme::V1Legacy,
            "event {seq} verified via {scheme:?}; a v0.6.4 ledger must use the legacy layout"
        );
    }
}

#[tokio::test]
#[serial]
async fn legacy_prose_denials_still_deserialize() {
    // 0.8.0 adds typed guard_denial and tripwire_rejection variants. Ledgers
    // from v0.6.4 recorded refusals as `thought` events with a text prefix, and
    // adding enum variants must not stop those parsing.
    let pool = pool().await;
    load_fixture(&pool).await;

    let found = events(&pool).await.into_iter().any(|(_, _, _, p, _, _)| {
        matches!(&p.0, EventPayload::Thought { content } if content.starts_with("Guard denied:"))
    });
    assert!(
        found,
        "fixture should contain a legacy prose denial - it is the shape the new \
         typed variants must stay compatible with"
    );
}

#[tokio::test]
#[serial]
async fn the_fixture_test_can_actually_detect_tampering() {
    // A migration test that cannot fail proves nothing. The immutability trigger
    // refuses the UPDATE - which is the database layer working - but it is no
    // defence against someone holding the credentials, and the hash chain is the
    // layer that has to catch that.
    let pool = pool().await;
    load_fixture(&pool).await;

    pool.execute("ALTER TABLE agent_events DISABLE TRIGGER USER")
        .await
        .expect("disabling the trigger on the scratch database");
    sqlx::query("UPDATE agent_events SET payload = $1::jsonb WHERE sequence = 1")
        .bind(r#"{"type":"thought","content":"tampered"}"#)
        .execute(&pool)
        .await
        .expect("tampering");
    pool.execute("ALTER TABLE agent_events ENABLE TRIGGER USER")
        .await
        .expect("re-enabling the trigger");

    let tip = events(&pool).await.last().expect("non-empty").0;
    assert!(
        !verify_chain(&pool, 0, tip).await.expect("verification"),
        "verification passed on a tampered ledger - the other tests here prove nothing"
    );
}
