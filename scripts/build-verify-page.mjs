#!/usr/bin/env node
// Build site/verify-bundle.js: the browser verifier's WebAssembly module, the
// sample certificates and the challenge's answer hash, as one script.
//
//     make wasm-verifier          # cargo build for wasm32, then this script
//
// Why one embedded script instead of fetching verify.wasm and the samples:
// the page promises that nothing leaves the browser, and the strongest form of
// that promise is a page that still works after "Save page as…" with the
// network off. Browsers refuse fetch() from file:// URLs; they do not refuse a
// <script src> next to the page. So everything the page needs arrives in the
// first load and its Content-Security-Policy forbids any request after it.
//
// The module is built from crates/elc-wasm, which wraps
// ectoledger_elc::verify::verify, the same function verify-cert calls.
// scripts/check-wasm-verifier.mjs holds the two to that.

import { createHash } from "node:crypto";
import { execFileSync } from "node:child_process";
import { readdirSync, readFileSync, statSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const WASM = join(ROOT, "target/wasm32-unknown-unknown/release/ectoledger_elc_wasm.wasm");
const OUT = join(ROOT, "site/verify-bundle.js");

const read = (p) => readFileSync(join(ROOT, p));
const sha256 = (buf) => createHash("sha256").update(buf).digest("hex");

// The crates the module is compiled from. Their hash, not the module's bytes,
// is what says whether the bundle is stale: compilers embed build paths, so
// two correct builds on two machines rarely match byte for byte.
export const SOURCE_DIRS = ["crates/elc", "crates/elc-wasm", "crates/core"];

export function sourceHash(root = ROOT) {
  const files = [];
  const walk = (dir) => {
    for (const n of readdirSync(join(root, dir)).sort()) {
      const rel = `${dir}/${n}`;
      if (statSync(join(root, rel)).isDirectory()) walk(rel);
      else if (/\.(rs|toml)$/.test(n)) files.push(rel);
    }
  };
  SOURCE_DIRS.forEach(walk);
  const h = createHash("sha256");
  // CRLF is folded to LF so a Windows checkout (core.autocrlf) hashes the
  // same sources to the same value.
  for (const f of files) {
    h.update(f + "\0").update(readFileSync(join(root, f), "utf8").replace(/\r\n/g, "\n")).update("\0");
  }
  return h.digest("hex");
}


// Paths are the source of truth; check-wasm-verifier.mjs fails if an
// embedded copy stops matching its file.
export const SAMPLES = [
  {
    id: "genuine",
    label: "Genuine",
    path: "examples/verified-session/session.elc",
    blurb: "A real signed session certificate.",
  },
  {
    id: "tampered",
    label: "One character changed",
    path: "examples/verified-session/session-tampered.elc",
    blurb: "The same file with one hex character of one event hash changed.",
  },
  {
    id: "forged",
    label: "Forged (challenge)",
    path: "examples/challenge/ledger-5-certificate.elc",
    blurb: "Built by hand to describe a real ledger. Unsigned, and its Merkle root is made up.",
  },
];

if (import.meta.url === `file://${process.argv[1]}`) {
  const wasm = readFileSync(WASM);
  const rustc = execFileSync("rustc", ["--version"], { encoding: "utf8" }).trim();
  const version = /^version\s*=\s*"([^"]+)"/m.exec(read("Cargo.toml").toString())[1];
  const bundle = {
    generatedBy: "scripts/build-verify-page.mjs",
    wasm: wasm.toString("base64"),
    wasmSha256: sha256(wasm),
    wasmBytes: wasm.length,
    sourceSha256: sourceHash(),
    crate: `ectoledger-elc-wasm ${version}`,
    rustc,
    samples: SAMPLES.map((s) => ({
      id: s.id,
      label: s.label,
      blurb: s.blurb,
      file: s.path.split("/").pop(),
      path: s.path,
      text: read(s.path).toString("utf8"),
    })),
    challengeAnswerSha256: read("examples/challenge/ANSWER.sha256").toString("utf8").trim(),
  };

  const js =
    "// GENERATED by scripts/build-verify-page.mjs. Do not edit; run `make wasm-verifier`.\n" +
    `// ${bundle.crate}, ${rustc}, wasm sha256 ${bundle.wasmSha256}\n` +
    `window.ELC_BUNDLE = ${JSON.stringify(bundle)};\n`;
  writeFileSync(OUT, js);
  console.log(
    `wrote ${OUT.replace(ROOT + "/", "")}: ${bundle.wasmBytes} byte module, sha256 ${bundle.wasmSha256}`,
  );
}
