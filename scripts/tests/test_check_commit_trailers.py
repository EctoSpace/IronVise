# --- every forbidden pattern -------------------------------------------------


@pytest.mark.parametrize("pattern, trailer", sorted(TRAILERS.items()), ids=sorted(TRAILERS))
def test_each_forbidden_trailer_fails(repo, pattern, trailer):
    sha = repo.commit(f"Fix the thing\n\nSome explanation.\n\n{trailer}\n")
    result = repo.check()
    assert result.returncode == 1, result.stdout
    assert "check-commit-trailers: FAILED" in result.stderr
    assert f"  {sha[:9]}  Fix the thing" in result.stderr
    assert f"↳ {pattern}" in result.stderr
    assert "1 commit(s) in HEAD~1..HEAD carry an attribution trailer." in result.stderr


@pytest.mark.parametrize("transform", [str.upper, str.lower, str.swapcase], ids=["upper", "lower", "swapcase"])
@pytest.mark.parametrize("pattern", sorted(TRAILERS), ids=sorted(TRAILERS))
def test_matching_is_case_insensitive(repo, pattern, transform):
    repo.commit(f"Subject\n\n{transform(TRAILERS[pattern])}\n")
    result = repo.check()
    assert result.returncode == 1
    assert f"↳ {pattern}" in result.stderr


def test_trailer_in_the_middle_of_a_long_message(repo):
    body = "\n".join(f"line {i}" for i in range(20))
    repo.commit(f"Long message\n\n{body}\n{TRAILERS[CO_CLAUDE]}\n{body}\n")
    assert repo.check().returncode == 1


def test_trailer_as_last_line_without_newline(repo):
    repo.commit(f"Subject\n\nBody.\n\nSigned-off-by: A <a@example.invalid>\n{TRAILERS[NOREPLY]}")
    assert repo.check().returncode == 1


def test_trailer_in_the_subject_line(repo):
    repo.commit(TRAILERS[GENERATED_PLAIN] + "\n")
    result = repo.check()
    assert result.returncode == 1
    assert TRAILERS[GENERATED_PLAIN] in result.stderr


def test_several_trailers_in_one_commit_are_all_listed(repo):
    repo.commit(
        "Subject\n\n"
        + TRAILERS[CO_CLAUDE] + "\n"
        + TRAILERS[SESSION_URL] + "\n"
    )
    result = repo.check()
    assert result.returncode == 1
    assert f"↳ {SESSION_URL}" in result.stderr
    assert f"↳ {CO_CLAUDE}" in result.stderr
    assert "1 commit(s)" in result.stderr


def test_crlf_message_is_still_caught(repo):
    repo.commit("Windows subject\r\n\r\nBody.\r\n\r\n" + TRAILERS[CO_COPILOT] + "\r\n")
    assert b"\r\n" in subprocess.run(
        ["git", "cat-file", "commit", "HEAD"], cwd=repo.path, env=repo.env, capture_output=True, check=True,
    ).stdout
    result = repo.check()
    assert result.returncode == 1
    assert f"↳ {CO_COPILOT}" in result.stderr


def test_crlf_clean_message_passes(repo):
    repo.commit("Windows subject\r\n\r\nNothing to see.\r\n")
    assert repo.check().returncode == 0


def test_long_subject_is_truncated_in_the_report(repo):
    subject = "x" * 100
    repo.commit(f"{subject}\n\n{TRAILERS[CO_CLAUDE]}\n")
    result = repo.check()
    assert "x" * 60 in result.stderr
    assert "x" * 61 not in result.stderr


# --- range selection ---------------------------------------------------------


def test_default_range_without_upstream_checks_only_the_tip(repo):
    repo.commit(f"Older\n\n{TRAILERS[CO_CLAUDE]}\n")
    repo.commit("Tip is clean\n")
    result = repo.check()
    assert result.returncode == 0, result.stderr
    assert "1 commit(s) in HEAD~1..HEAD" in result.stdout


def test_default_range_uses_the_upstream(tmp_path, repo):
    remote = tmp_path / "remote.git"
    subprocess.run(["git", "init", "-q", "--bare", str(remote)], env=repo.env, check=True)
    repo.commit(f"Already pushed\n\n{TRAILERS[CO_CLAUDE]}\n")
    repo.git("remote", "add", "origin", str(remote))
    repo.git("push", "-q", "-u", "origin", "main")

    result = repo.check()
    assert result.returncode == 0, result.stderr
    assert "0 commit(s) in origin/main..HEAD" in result.stdout

    repo.commit("Unpushed and clean\n")
    sha = repo.commit(f"Unpushed and dirty\n\n{TRAILERS[GENERATED_LINK]}\n")
    result = repo.check()
    assert result.returncode == 1
    assert sha[:9] in result.stderr
    assert "Already pushed" not in result.stderr
    assert "1 commit(s) in origin/main..HEAD carry" in result.stderr


def test_all_mode_scans_the_whole_history(repo):
    old = repo.commit(f"Old offender\n\n{TRAILERS[CO_CHATGPT]}\n")
    repo.commit("Clean\n")
    repo.commit("Clean again\n")
    assert repo.check().returncode == 0
    result = repo.check("--all")
    assert result.returncode == 1
    assert old[:9] in result.stderr
    assert "1 commit(s) in --all carry" in result.stderr


def test_all_mode_includes_other_branches(repo):
    repo.git("checkout", "-q", "-b", "side")
    side = repo.commit(f"Side branch\n\n{TRAILERS[SESSION_URL]}\n")
    repo.git("checkout", "-q", "main")
    result = repo.check("--all")
    assert result.returncode == 1
    assert side[:9] in result.stderr


def test_all_mode_clean_history_counts_every_commit(repo):
    repo.commit("Two\n")
    repo.commit("Three\n")
    result = repo.check("--all")
    assert result.returncode == 0
    assert "3 commit(s) in --all" in result.stdout


def test_explicit_range(repo):
    base = repo.git("rev-parse", "HEAD")
    first = repo.commit(f"In range\n\n{TRAILERS[ROBOT]}\n")
    repo.commit("Also in range\n")
    result = repo.check(f"{base}..HEAD")
    assert result.returncode == 1
    assert first[:9] in result.stderr
    assert f"1 commit(s) in {base}..HEAD carry" in result.stderr

    result = repo.check(f"{first}..HEAD")
    assert result.returncode == 0
    assert f"1 commit(s) in {first}..HEAD" in result.stdout


def test_empty_range_passes(repo):
    result = repo.check("HEAD..HEAD")
    assert result.returncode == 0
    assert "0 commit(s) in HEAD..HEAD" in result.stdout


