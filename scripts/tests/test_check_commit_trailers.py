"""Tests for scripts/check-commit-trailers.py in throwaway git repositories.

The forbidden trailers are assembled by concatenation so that this file never
contains one verbatim.
"""

from __future__ import annotations

import importlib.util
import shutil
import subprocess
import sys
from pathlib import Path

import pytest

SCRIPT = Path(__file__).resolve().parent.parent / "check-commit-trailers.py"

pytestmark = pytest.mark.skipif(shutil.which("git") is None, reason="git is not installed")

CO = "Co-Authored-" + "By"
CO_CLAUDE = "co-authored-by: " + "claude"
CO_CHATGPT = "co-authored-by: " + "chatgpt"
CO_COPILOT = "co-authored-by: " + "copilot"
SESSION_URL = "claude.ai/code/" + "session"
GENERATED_LINK = "generated with " + "[claude"
GENERATED_PLAIN = "generated with " + "claude"
ROBOT = "\U0001F916 " + "generated"
NOREPLY = "noreply@" + "anthropic.com"

# The script's FORBIDDEN pattern -> a realistic footer line that contains it.
TRAILERS = {
    CO_CLAUDE: f"{CO}: " + "Claude <bot@example.invalid>",
    CO_CHATGPT: f"{CO}: " + "ChatGPT <bot@example.invalid>",
    CO_COPILOT: f"{CO}: " + "Copilot <bot@example.invalid>",
    SESSION_URL: "Session: https://" + SESSION_URL + "_0123",
    GENERATED_LINK: "Generated with " + "[Claude Code](https://example.invalid)",
    GENERATED_PLAIN: "Generated with " + "Claude Code",
    ROBOT: "\U0001F916 " + "Generated by a tool",
    NOREPLY: "Reviewed-by: Bot <" + NOREPLY + ">",
}


class Repo:
    def __init__(self, path: Path, env: dict[str, str]) -> None:
        self.path = path
        self.env = env
        path.mkdir(parents=True, exist_ok=True)
        self.git("init", "-q", "-b", "main")

    def git(self, *args: str) -> str:
        return subprocess.run(
            ["git", *args], cwd=self.path, env=self.env, check=True,
            capture_output=True, text=True, encoding="utf-8",
        ).stdout.strip()

    def commit(self, message: str) -> str:
        # -F with a file keeps the message byte-exact (CRLF included);
        # --cleanup=verbatim stops git rewriting it.
        msg = self.path.parent / "msg.txt"
        msg.write_bytes(message.encode("utf-8"))
        self.git("commit", "-q", "--allow-empty", "--cleanup=verbatim", "-F", str(msg))
        return self.git("rev-parse", "HEAD")

    def check(self, *args: str, env: dict[str, str] | None = None) -> subprocess.CompletedProcess[str]:
        return subprocess.run(
            [sys.executable, str(SCRIPT), *args], cwd=self.path, env=env or self.env,
            capture_output=True, text=True, encoding="utf-8", timeout=60,
        )


@pytest.fixture
def repo(tmp_path: Path, git_env: dict[str, str]) -> Repo:
    r = Repo(tmp_path / "repo", git_env)
    r.commit("Initial commit\n")
    return r


def test_fixture_covers_every_forbidden_pattern():
    spec = importlib.util.spec_from_file_location("check_commit_trailers", SCRIPT)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    assert set(TRAILERS) == set(module.FORBIDDEN)


