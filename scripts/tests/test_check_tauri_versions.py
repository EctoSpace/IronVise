"""Tests for scripts/check-tauri-versions.py against fixture repository trees."""

from __future__ import annotations

import json
from pathlib import Path

import pytest

VERSION = "0.8.0"

DEFAULT_CRATES = {
    "tauri": "2.10.3",
    "tauri-plugin-fs": "2.4.1",
    "tauri-plugin-dialog": "2.3.0",
    "tauri-plugin-shell": "2.3.2",
}
DEFAULT_NPM = {
    "@tauri-apps/api": "2.10.1",
    "@tauri-apps/plugin-fs": "2.4.0",
    "@tauri-apps/plugin-dialog": "2.3.5",
    "@tauri-apps/plugin-shell": "2.3.0",
}


def cargo_lock(packages: dict[str, str]) -> str:
    blocks = ["# This file is automatically @generated by Cargo.\nversion = 4\n"]
    for name, version in packages.items():
        blocks.append(
            f'[[package]]\nname = "{name}"\nversion = "{version}"\n'
            f'source = "registry+https://github.com/rust-lang/crates.io-index"\n'
        )
    return "\n".join(blocks)


def npm_lock(root_version: str, packages: dict[str, str], extra: dict | None = None) -> str:
    tree: dict = {"": {"name": "fixture", "version": root_version}}
    for name, version in packages.items():
        tree[f"node_modules/{name}"] = {"version": version}
    tree.update(extra or {})
    return json.dumps({"name": "fixture", "version": root_version, "lockfileVersion": 3, "packages": tree})


class Tree:
    """A minimal repository containing every file the script reads."""

    def __init__(self, root: Path, script: Path, run_script) -> None:
        self.root = root
        self.script = script
        self._run = run_script
        self.newline = "\n"

    def write(self, rel: str, text: str) -> Path:
        path = self.root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(text.replace("\n", self.newline).encode("utf-8"))
        return path

    def populate(self, *, version: str = VERSION, crates: dict | None = None,
                 npm: dict | None = None, overrides: dict[str, str] | None = None) -> None:
        crates = DEFAULT_CRATES if crates is None else crates
        npm = DEFAULT_NPM if npm is None else npm
        files = {
            "Cargo.toml": f'[workspace]\nmembers = ["crates/*"]\n\n[workspace.package]\nversion = "{version}"\nedition = "2024"\n',
            "gui/src-tauri/Cargo.toml": f'[package]\nname = "ectoledger-gui"\nversion = "{version}"\n\n[dependencies]\ntauri = "2"\n',
            "sdk/python/pyproject.toml": f'[build-system]\nrequires = ["hatchling"]\n\n[project]\nname = "ironvise"\nversion = "{version}"\n',
            "crates/guest/Cargo.toml": f'[package]\nname = "guest"\nversion = "{version}"\n',
            "crates/guard_unikernel/Cargo.toml": f'[package]\nname = "guard_unikernel"\nversion = "{version}"\n',
            "crates/guard_unikernel/Cargo.lock": cargo_lock({"guard_unikernel": version}),
            "gui/src-tauri/tauri.conf.json": json.dumps({"productName": "EctoLedger", "version": version}),
            "gui/package.json": json.dumps({"name": "gui", "version": version}),
            "gui/package-lock.json": npm_lock(version, npm),
            "sdk/typescript/package.json": json.dumps({"name": "sdk", "version": version}),
            "sdk/typescript/package-lock.json": npm_lock(version, {}),
            "sdk/python/ironvise_sdk/__init__.py": f'"""SDK."""\n\n__version__ = "{version}"\n',
            "Cargo.lock": cargo_lock({"serde": "1.0.0", **crates}),
        }
        files.update(overrides or {})
        for rel, text in files.items():
            self.write(rel, text)

    def run(self):
        return self._run(self.script, cwd=self.root / "scripts")


@pytest.fixture
def tree(tmp_path: Path, install_script, run_script) -> Tree:
    return Tree(tmp_path, install_script("check-tauri-versions.py"), run_script)


# --- passing trees -----------------------------------------------------------


def test_consistent_tree_passes(tree):
    tree.populate()
    result = tree.run()
    assert result.returncode == 0, result.stderr
    assert result.stdout.startswith(
        f"check-tauri-versions: OK - 12 release metadata sources agree on {VERSION}; "
        "4 Rust/npm package pair(s) agree on major.minor."
    )


def test_crlf_files_pass(tree):
    tree.newline = "\r\n"
    tree.populate()
    result = tree.run()
    assert result.returncode == 0, result.stderr


def test_patch_level_differences_are_allowed(tree):
    tree.populate(crates={"tauri": "2.10.99"}, npm={"@tauri-apps/api": "2.10.0"})
    result = tree.run()
    assert result.returncode == 0, result.stderr
    assert "1 Rust/npm package pair(s)" in result.stdout


def test_pairs_absent_on_both_sides_are_skipped(tree):
    tree.populate(crates={}, npm={})
    result = tree.run()
    assert result.returncode == 0, result.stderr
    assert "0 Rust/npm package pair(s)" in result.stdout


def test_prerelease_versions_compare_on_major_minor(tree):
    tree.populate(crates={"tauri": "2.0.0-rc.3"}, npm={"@tauri-apps/api": "2.0.1"})
    assert tree.run().returncode == 0


def test_nested_npm_copies_do_not_shadow_the_top_level_package(tree):
    tree.populate()
    nested = {"node_modules/some-lib/node_modules/@tauri-apps/api": {"version": "1.5.0"}}
    tree.write("gui/package-lock.json", npm_lock(VERSION, DEFAULT_NPM, nested))
    result = tree.run()
    assert result.returncode == 0, result.stderr


def test_other_cargo_toml_sections_do_not_supply_the_version(tree):
    # [package.metadata] and [dependencies] tables carry their own `version`
    # keys; only the named section's literal version counts.
    tree.populate(overrides={
        "gui/src-tauri/Cargo.toml": (
            '[package.metadata.bundle]\nversion = "9.9.9"\n\n'
            f'[package]\nname = "ectoledger-gui"\nversion = "{VERSION}"\n\n'
            '[dependencies.tauri]\nversion = "2.10"\n'
        ),
    })
    assert tree.run().returncode == 0


# --- failing trees -----------------------------------------------------------


@pytest.mark.parametrize(
    "crate, crate_v, package, npm_v",
    [
        ("tauri", "2.11.5", "@tauri-apps/api", "2.10.1"),
        ("tauri-plugin-fs", "2.4.0", "@tauri-apps/plugin-fs", "2.5.0"),
        ("tauri-plugin-shell", "3.0.0", "@tauri-apps/plugin-shell", "2.0.0"),
    ],
    ids=["core-minor", "plugin-minor", "plugin-major"],
)
def test_rust_npm_major_minor_mismatch_fails(tree, crate, crate_v, package, npm_v):
    tree.populate(crates={**DEFAULT_CRATES, crate: crate_v}, npm={**DEFAULT_NPM, package: npm_v})
    result = tree.run()
    assert result.returncode == 1
    assert "check-tauri-versions: FAILED" in result.stderr
    assert "disagree on major/minor" in result.stderr
    assert f"  {crate} (v{crate_v}) : {package} (v{npm_v})" in result.stderr
    assert "Release metadata is inconsistent" not in result.stderr


@pytest.mark.parametrize(
    "rel, text, label, found",
    [
        ("gui/src-tauri/tauri.conf.json", json.dumps({"version": "0.7.9"}), "Tauri config", "0.7.9"),
        ("gui/package.json", json.dumps({"version": "0.8.1"}), "GUI npm package", "0.8.1"),
        ("sdk/python/ironvise_sdk/__init__.py", '__version__ = "0.6.3"\n', "Python SDK runtime", "0.6.3"),
        ("crates/guest/Cargo.toml", '[package]\nname = "guest"\nversion = "0.1.0"\n', "zkVM guest crate", "0.1.0"),
        ("crates/guard_unikernel/Cargo.lock", cargo_lock({"guard_unikernel": "0.6.3"}),
         "guard unikernel lock", "0.6.3"),
        ("sdk/typescript/package-lock.json", npm_lock("0.7.0", {}), "TypeScript SDK lock", "0.7.0"),
    ],
    ids=["tauri-conf", "gui-package", "python-runtime", "guest", "unikernel-lock", "ts-lock"],
)
def test_release_metadata_mismatch_fails(tree, rel, text, label, found):
    tree.populate(overrides={rel: text})
    result = tree.run()
    assert result.returncode == 1
    assert "Release metadata is inconsistent" in result.stderr
    assert f"  {label}: {found} (expected {VERSION})" in result.stderr


def test_workspace_version_is_the_reference(tree):
    tree.populate()
    tree.write("Cargo.toml", '[workspace.package]\nversion = "0.9.0"\n')
    result = tree.run()
    assert result.returncode == 1
    assert f"Tauri config: {VERSION} (expected 0.9.0)" in result.stderr
    assert "Rust workspace:" not in result.stderr


